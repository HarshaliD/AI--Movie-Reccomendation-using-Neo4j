import os
from pathlib import Path
from dotenv import load_dotenv
from neo4j import GraphDatabase
from google import genai

# Robust .env loading: checks current working directory, script directory, and parent directory
load_dotenv()
if not os.getenv("NEO4J_URI"):
    base_dir = Path(__file__).resolve().parent
    for candidate in [base_dir / ".env", base_dir.parent / ".env", base_dir / "movie-recommendation" / ".env"]:
        if candidate.is_file():
            load_dotenv(dotenv_path=candidate)
            break

# Neo4j configuration
URI = os.getenv("NEO4J_URI")
USERNAME = os.getenv("NEO4J_USERNAME")
PASSWORD = os.getenv("NEO4J_PASSWORD")
DATABASE = os.getenv("NEO4J_DATABASE", "neo4j")

# Gemini configuration
GEMINI_API_KEY = os.getenv("GEMINI_API_KEY")
GEMINI_MODEL = "gemini-3.1-flash-lite"

# Validate configuration
if not all([URI, USERNAME, PASSWORD]):
    raise ValueError("Missing Neo4j credentials in .env")

if not GEMINI_API_KEY:
    raise ValueError("Missing GEMINI_API_KEY in .env")


# Factory functions for client initialization
def get_driver():
    """Create and return a Neo4j driver instance using env credentials."""
    return GraphDatabase.driver(
        URI,
        auth=(USERNAME, PASSWORD)
    )


def get_gemini_client():
    """Create and return a Gemini API client instance using env credentials."""
    return genai.Client(api_key=GEMINI_API_KEY)


# Retrieve up to three movies sharing actors or genres
RECOMMENDATION_QUERY = """
MATCH (selected:Movie {title: $movie_title})
MATCH (recommended:Movie)
WHERE recommended <> selected

OPTIONAL MATCH
    (selected)<-[:ACTED_IN]-(actor:Actor)-[:ACTED_IN]->(recommended)

OPTIONAL MATCH
    (selected)-[:IN_GENRE]->(genre:Genre)<-[:IN_GENRE]-(recommended)

WITH recommended,
     collect(DISTINCT actor.name) AS sharedActors,
     collect(DISTINCT genre.name) AS sharedGenres

WHERE size(sharedActors) > 0 OR size(sharedGenres) > 0

RETURN recommended.title AS movie,
       sharedActors,
       sharedGenres

ORDER BY size(sharedActors) + size(sharedGenres) DESC
LIMIT 3
"""


def get_recommendations(session, movie_title):
    """Retrieve recommendations and their graph evidence."""
    result = session.run(
        RECOMMENDATION_QUERY,
        movie_title=movie_title
    )

    return [record.data() for record in result]


def check_movie_exists(session, movie_title):
    """Check whether a movie exists in the database."""
    movie_record = session.run(
        """
        MATCH (m:Movie {title: $title})
        RETURN m.title AS title
        """,
        title=movie_title
    ).single()
    return movie_record is not None


def get_available_movies(session):
    """Retrieve all available movie titles from Neo4j."""
    result = session.run(
        """
        MATCH (m:Movie)
        RETURN m.title AS title
        ORDER BY title
        """
    )
    return [record["title"] for record in result if record.get("title")]


def explain_recommendation(selected_title, recommendation, client):
    """Use Gemini to interpret the evidence returned by Neo4j."""
    if client is None:
        raise ValueError("A valid Gemini client must be provided to explain_recommendation.")

    evidence = {
        "selected_movie": selected_title,
        "recommended_movie": recommendation["movie"],
        "shared_actors": recommendation["sharedActors"],
        "shared_genres": recommendation["sharedGenres"]
    }

    prompt = f"""
You explain recommendations generated by a movie knowledge graph.

SELECTED MOVIE: {evidence["selected_movie"]}
RECOMMENDED MOVIE: {evidence["recommended_movie"]}
SHARED ACTORS: {evidence["shared_actors"]}
SHARED GENRES: {evidence["shared_genres"]}

The recommendation was generated because these movies share
at least one actor or genre.

Your job is to interpret the evidence, not merely rephrase it.

Consider:
- What kind of connection exists between the movies?
- If actors are shared, explain the cast connection.
- If genres are shared, explain the category connection.
- If both are shared, explain how these provide different
  reasons to consider the recommendation.
- What can the user reasonably conclude from these connections?
- What cannot be concluded from the available evidence?

Rules:
- Use only the facts supplied above.
- Do not invent plots, themes, release years, or relationships.
- Do not claim shared actors imply similar stories or acting styles.
- Do not guarantee the user will enjoy the recommendation.
- Do not make unsupported claims about recommendation quality.
- Be specific to these two movie titles.
- Avoid generic filler and repetitive sentence templates.
- Explain the significance and limitations of the evidence.
- Write 2-3 concise, natural sentences.
- Return only the explanation, without a heading or bullets.
"""

    response = client.models.generate_content(
        model=GEMINI_MODEL,
        contents=prompt
    )

    if not response.text or not response.text.strip():
        raise RuntimeError("Gemini returned an empty explanation.")

    return response.text.strip()


def main():
    driver = None
    gemini = None
    try:
        driver = get_driver()
        gemini = get_gemini_client()

        # Verify the Neo4j connection
        driver.verify_connectivity()
        print("Connected to Neo4j AuraDB!")

        with driver.session(database=DATABASE) as session:
            movie_title = input(
                "\nEnter a movie you like: "
            ).strip()

            if not movie_title:
                print("Please enter a movie title.")
                return

            # Check whether the selected movie exists
            if not check_movie_exists(session, movie_title):
                print(
                    f"\n'{movie_title}' is not in our movie database. "
                    "Please try a movie from our available collection."
                )
                return

            # Fetch graph-based recommendations
            recommendations = get_recommendations(
                session,
                movie_title
            )

        if not recommendations:
            print(
                f"\nNo recommendations found for '{movie_title}'. "
                "Our database may not contain enough actor or "
                "genre connections for this movie."
            )
            return

        print(f"\nRecommendations based on {movie_title}:\n")

        for index, movie in enumerate(recommendations, start=1):
            print(f"{index}. {movie['movie']}")

            print(
                "   Shared actors: "
                + (", ".join(movie["sharedActors"]) or "None")
            )

            print(
                "   Shared genres: "
                + (", ".join(movie["sharedGenres"]) or "None")
            )

            try:
                explanation = explain_recommendation(
                    movie_title,
                    movie,
                    client=gemini
                )
                print(f"   Why consider it: {explanation}")

            except Exception as error:
                # Keep graph recommendations even if Gemini fails
                print(
                    "   Explanation unavailable. "
                    "The Neo4j recommendation is still valid."
                )
                print(f"   Details: {error}")

            print()

    except Exception as error:
        print(f"\nApplication error: {error}")

    finally:
        if driver is not None:
            driver.close()
        if gemini is not None:
            gemini.close()


if __name__ == "__main__":
    main()
